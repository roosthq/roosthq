// Writes web/public/learning/CREDITS.md and manifest.json from every QA'd media manifest
// (animals: one object per file; visual sets: an array per file).
const fs = require('fs');
const S = 'C:/Users/sheac/AppData/Local/Temp/claude/C--Users-sheac-Github-Personal/d3295f37-d84f-43de-aa58-cf3e2dc83375/scratchpad';
const REPO = 'C:/Users/sheac/Github Personal/Family Calendar System';
const PUB = REPO + '/web/public/';
const esc = (s) => String(s || '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
const exists = (f) => f && fs.existsSync(PUB + f);

const animals = [];
const items = [];
for (const f of fs.readdirSync(S + '/media/manifest').filter((x) => x.endsWith('.json'))) {
  let d;
  try {
    d = JSON.parse(fs.readFileSync(S + '/media/manifest/' + f, 'utf8'));
  } catch {
    continue;
  }
  if (Array.isArray(d)) for (const x of d) items.push({ set: f.replace('.json', ''), ...x });
  else if (d && d.image) animals.push(d);
}
animals.sort((a, b) => a.name.localeCompare(b.name));
items.sort((a, b) => a.set.localeCompare(b.set) || String(a.name).localeCompare(String(b.name)));

let md = `# Learning media credits\n\nEvery photograph, diagram and animal sound used in Roost HQ's Learning questions is a real, freely licensed file from [Wikimedia Commons](https://commons.wikimedia.org/). Images were cropped or fitted to 4:3 and converted to WebP; sounds were trimmed, loudness-normalized, and converted to MP3. Each work stays under its original license (linked below). Nothing here is synthesized. The math and logic pictures (clocks, fractions, graphs, patterns) are original drawings generated by the app's own tooling.\n\n## Animals (photos and sounds)\n\n| Animal | Photo | Photo author | Photo license | Sound | Sound author | Sound license |\n|---|---|---|---|---|---|---|\n`;
let keptAnimals = 0;
for (const a of animals) {
  if (!exists(a.image.file)) continue;
  keptAnimals++;
  const au = a.audio && exists(a.audio.file) ? a.audio : null;
  md += `| ${esc(a.name)} | [${esc(a.image.title)}](${a.image.sourceUrl}) | ${esc(a.image.author)} | ${esc(a.image.license)} | ${au ? `[${esc(au.title)}](${au.sourceUrl})` : '-'} | ${au ? esc(au.author) : '-'} | ${au ? esc(au.license) : '-'} |\n`;
}
md += `\n## Other photo and diagram sets\n\n| Set | Item | File | Author | License |\n|---|---|---|---|---|\n`;
let keptItems = 0;
for (const x of items) {
  if (!exists(x.file)) continue;
  keptItems++;
  md += `| ${esc(x.set)} | [${esc(x.title || x.name)}](${x.sourceUrl}) | ${esc(x.file)} | ${esc(x.author)} | ${esc(x.license)} |\n`;
}
fs.writeFileSync(PUB + 'learning/CREDITS.md', md);
fs.writeFileSync(PUB + 'learning/manifest.json', JSON.stringify({ animals: animals.filter((a) => exists(a.image.file)), items: items.filter((x) => exists(x.file)) }, null, 1));
console.log(`credits: ${keptAnimals} animals (${animals.filter((a) => a.audio && exists(a.audio.file)).length} with sound), ${keptItems} other items`);
